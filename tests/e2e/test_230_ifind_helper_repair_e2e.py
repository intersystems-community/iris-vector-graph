"""Spec 230 FR-030 gate — a package compile kills iFind search, and the repair revives it.

The defect is a class-compiler side effect, so it cannot be seen from Python. `%FIND
search_index(idx, term)` does not reach the index directly: it calls a *generated*
class — `<owner>.<hash>`, `GeneratedBy = '<owner>.CLS'`, extending `%iFind.Find.Basic`
— that the compiler writes while compiling the owner of the index. A second
`$SYSTEM.OBJ.CompilePackage("Graph.KG", "ck-d")` deletes that compiled helper and
writes no replacement, because the owner it would be regenerated from is already up to
date. `%Dictionary.CompiledIndex` still lists the index and the class definition is
intact, so no status, no report and no `SHOW INDEXES` notices; the first thing that
notices is a query, at Open:

    [SQLCODE: <-149>] ... <CLASS DOES NOT EXIST> idxdocstextifindEmbedded+2^...

Two package compiles is not a contrived sequence. `initialize_schema` deploys the
ObjectScript layer (one compile) and the `^KG` re-key recompiles the package (a second),
and any `LoadDir` deploy over an up-to-date tree does it on its own — which is why this
reached every upgraded *and* every re-deployed install as a silently dead text leg.

Worse than dead: `_text_search` treats any error mentioning FIND as "no iFind index
here" and falls back to `LIKE`, which matches substrings and scores every hit 1.0. So
the leg keeps answering, with different results, and reports nothing.

Both of the schema's iFind indexes are covered: `idx_docs_text_ifind` (the `kg_TXT`
leg) and `idx_props_val_ifind` (property text search).
"""

from __future__ import annotations

import contextlib
import os

import pytest

pytestmark = [pytest.mark.e2e]

GRAPH = "ivg230:ifind"

DOC_ID = "ivg230:ifind:doc"
NODE_ID = "ivg230:ifind:node"

#: Appears in no other row in the namespace, so a hit is this fixture's row and a
#: miss is the index, not the corpus.
TERM = "ivg230quokkaword"

DOCS_OWNER_INDEX = "idx_docs_text_ifind"
PROPS_OWNER_INDEX = "idx_props_val_ifind"


def _require_iris(iris_connection):
    if os.environ.get("SKIP_IRIS_TESTS", "false").lower() == "true":
        pytest.fail(
            "FR-030 is a class-compiler side effect: a generated class is deleted and "
            "not rewritten. SKIP_IRIS_TESTS=true cannot observe it — start "
            "ivg-iris-enterprise with scripts/enterprise-container.sh up."
        )
    if iris_connection is None:
        pytest.fail("no live IRIS connection: the defect is in the class compiler.")


def _exec(conn, sql, params=None):
    cursor = conn.cursor()
    try:
        cursor.execute(sql, params or [])
        with contextlib.suppress(Exception):
            return cursor.fetchall()
    finally:
        with contextlib.suppress(Exception):
            cursor.close()


def _wipe(conn):
    for sql, params in (
        ("DELETE FROM Graph_KG.docs WHERE id = ?", [DOC_ID]),
        ("DELETE FROM Graph_KG.rdf_props WHERE s = ?", [NODE_ID]),
    ):
        with contextlib.suppress(Exception):
            _exec(conn, sql, params)
    with contextlib.suppress(Exception):
        conn.commit()


def _break_the_helpers(conn):
    """Compile `Graph.KG` twice — the second pass is what deletes the helper classes."""
    from iris_vector_graph.schema import _call_classmethod

    for _ in range(2):
        _call_classmethod(conn, "%SYSTEM.OBJ", "CompilePackage", "Graph.KG", "ck-d")
    with contextlib.suppress(Exception):
        conn.commit()


def _helper_count(conn, index_name: str) -> int:
    """Compiled `%iFind.Find` helpers generated by the class owning `index_name`."""
    from iris_vector_graph.schema import _IFIND_HELPER_SQL

    cursor = conn.cursor()
    try:
        cursor.execute(_IFIND_HELPER_SQL, ["Graph_KG"])
        for row in cursor.fetchall() or []:
            if str(row[1]) == index_name:
                return int(row[2] or 0)
    finally:
        with contextlib.suppress(Exception):
            cursor.close()
    pytest.fail(f"{index_name} is not defined in this namespace — nothing to repair")


def _find_docs(conn):
    """`%FIND` against the docs index, raising whatever IRIS raises."""
    cursor = conn.cursor()
    try:
        cursor.execute(
            "SELECT d.id FROM Graph_KG.docs d "
            "WHERE %ID %FIND search_index(idx_docs_text_ifind, ?)",
            [TERM],
        )
        return [row[0] for row in cursor.fetchall() or []]
    finally:
        with contextlib.suppress(Exception):
            cursor.close()


def _find_props(conn):
    cursor = conn.cursor()
    try:
        cursor.execute(
            "SELECT p.s FROM Graph_KG.rdf_props p "
            "WHERE %ID %FIND search_index(idx_props_val_ifind, ?)",
            [TERM],
        )
        return [row[0] for row in cursor.fetchall() or []]
    finally:
        with contextlib.suppress(Exception):
            cursor.close()


def _repair(conn) -> dict:
    from iris_vector_graph.schema import repair_ifind_helpers

    cursor = conn.cursor()
    try:
        return repair_ifind_helpers(cursor, conn=conn)
    finally:
        with contextlib.suppress(Exception):
            cursor.close()


@pytest.fixture
def searchable_rows(iris_connection):
    """One document and one property holding :data:`TERM`, with the indexes working.

    The fixture repairs before it asserts: the namespace may already carry the damage
    from an earlier deploy, and a test that started from an unknown state could not
    tell a repair from a no-op.
    """
    _require_iris(iris_connection)
    _wipe(iris_connection)

    _exec(
        iris_connection,
        "INSERT INTO Graph_KG.docs (graph_id, id, text) VALUES (?, ?, ?)",
        [GRAPH, DOC_ID, f"a document mentioning {TERM} once"],
    )
    _exec(
        iris_connection,
        "INSERT INTO Graph_KG.rdf_props (graph_id, s, key, val) VALUES (?, ?, ?, ?)",
        [GRAPH, NODE_ID, "note", f"a property mentioning {TERM} once"],
    )
    with contextlib.suppress(Exception):
        iris_connection.commit()

    _repair(iris_connection)
    assert _find_docs(iris_connection) == [DOC_ID], (
        "the fixture could not establish a working docs index, so nothing below can "
        "distinguish the defect from a missing index"
    )
    assert _find_props(iris_connection) == [NODE_ID]

    yield iris_connection

    _wipe(iris_connection)


class TestASecondPackageCompileBreaksTextSearch:
    """The defect itself, reproduced: two compiles and the leg is gone."""

    def test_the_docs_helper_class_disappears(self, searchable_rows):
        conn = searchable_rows
        assert _helper_count(conn, DOCS_OWNER_INDEX) > 0
        _break_the_helpers(conn)
        assert _helper_count(conn, DOCS_OWNER_INDEX) == 0, (
            "a second CompilePackage should have deleted the generated helper class — "
            "if it did not, this IRIS build no longer has the defect and FR-030's "
            "repair is redundant rather than wrong"
        )

    def test_the_index_definition_survives_so_nothing_reports_it(self, searchable_rows):
        """Why it is silent: the index is still there, only the helper is gone."""
        conn = searchable_rows
        _break_the_helpers(conn)
        cursor = conn.cursor()
        try:
            cursor.execute(
                "SELECT COUNT(*) FROM %Dictionary.CompiledIndex "
                "WHERE SqlName = ? AND TypeClass LIKE '%iFind%'",
                [DOCS_OWNER_INDEX],
            )
            assert cursor.fetchone()[0] >= 1
        finally:
            with contextlib.suppress(Exception):
                cursor.close()

    def test_the_query_fails_at_open(self, searchable_rows):
        conn = searchable_rows
        _break_the_helpers(conn)
        with pytest.raises(Exception) as excinfo:
            _find_docs(conn)
        assert "-149" in str(excinfo.value) or "DOES NOT EXIST" in str(excinfo.value).upper()


class TestTheRepairMakesTheIndexSearchableAgain:
    def test_the_docs_leg_answers_again(self, searchable_rows):
        conn = searchable_rows
        _break_the_helpers(conn)
        result = _repair(conn)
        assert result.get(DOCS_OWNER_INDEX) is True, result
        assert _find_docs(conn) == [DOC_ID]

    def test_the_props_leg_answers_again(self, searchable_rows):
        """Both indexes are affected — repairing only the one kg_TXT uses is half a fix."""
        conn = searchable_rows
        _break_the_helpers(conn)
        result = _repair(conn)
        assert result.get(PROPS_OWNER_INDEX) is True, result
        assert _find_props(conn) == [NODE_ID]

    def test_a_second_repair_is_a_no_op_and_leaves_it_working(self, searchable_rows):
        """Idempotent: the repair compiles the owner, and compiling an owner twice is safe."""
        conn = searchable_rows
        _break_the_helpers(conn)
        _repair(conn)
        again = _repair(conn)
        assert again.get(DOCS_OWNER_INDEX) is True
        assert _find_docs(conn) == [DOC_ID]

    def test_a_healthy_namespace_reports_every_index_searchable(self, searchable_rows):
        conn = searchable_rows
        result = _repair(conn)
        assert DOCS_OWNER_INDEX in result and PROPS_OWNER_INDEX in result, result
        assert all(result.values()), result
